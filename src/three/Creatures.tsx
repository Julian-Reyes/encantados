// Procedural low-poly creature models. Each faces +z with its feet at y = 0.
// Built from spheres/cones/boxes so no model files are needed.

import { useRef, type ReactNode } from "react";
import { useFrame } from "@react-three/fiber";
import type * as THREE from "three";
import type { SpeciesId } from "../data/species";
import { Bx, Cn, Cn4, Cy, Eye, Rk, Sph, SphHi, Tor } from "./prims";

type V3 = [number, number, number];

function Flame({ p, s = 1 }: { p: V3; s?: number }) {
  const ref = useRef<THREE.Group>(null);
  useFrame(({ clock }) => {
    const t = clock.elapsedTime;
    if (ref.current) {
      ref.current.scale.set(s * (1 + Math.sin(t * 17) * 0.08), s * (1 + Math.sin(t * 13) * 0.15), s * (1 + Math.cos(t * 19) * 0.08));
      ref.current.rotation.y = t * 3;
    }
  });
  return (
    <group ref={ref} position={p}>
      <Cn p={[0, 0.1, 0]} s={[0.1, 0.26, 0.1]} c="#ff7a1a" g />
      <Cn p={[0, 0.07, 0]} s={[0.065, 0.18, 0.065]} c="#ffd23a" g />
      <SphHi p={[0, -0.02, 0]} s={0.08} c="#ff9a2a" g />
    </group>
  );
}

function Wing({ p, side, children, flap = 0 }: { p: V3; side: 1 | -1; children: ReactNode; flap?: number }) {
  const ref = useRef<THREE.Group>(null);
  useFrame(({ clock }) => {
    if (ref.current && flap) ref.current.rotation.z = side * (Math.sin(clock.elapsedTime * flap) * 0.45 + 0.2);
  });
  return (
    <group ref={ref} position={p}>
      {children}
    </group>
  );
}

