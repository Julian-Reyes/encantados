/** A creature with a gentle idle bounce. */
export function CreatureModel({ species, idle = true }: { species: SpeciesId; idle?: boolean }) {
  const ref = useRef<THREE.Group>(null);
  const seed = useRef(Math.random() * 10);
  useFrame(({ clock }) => {
    if (!ref.current || !idle) return;
    const t = clock.elapsedTime + seed.current;
    ref.current.scale.set(1 + Math.sin(t * 3) * 0.02, 1 - Math.sin(t * 3) * 0.025, 1 + Math.sin(t * 3) * 0.02);
  });
  const M = MODELS[species];
  return (
    <group ref={ref}>
      <M />
    </group>
  );
}
